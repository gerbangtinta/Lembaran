// Records every code file at or above 1000 lines into AGENTS/LARGEFILES.md.
// A stale table fails --check, which `npm test` runs.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const TARGET = join(ROOT, 'AGENTS', 'LARGEFILES.md');
const THRESHOLD = 1000;
const SKIP = new Set(['node_modules', 'dist', '.git', '.tmp', 'coverage']);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry)) continue;
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) walk(full, out);
    else if (/\.(ts|tsx|mts|js|mjs|css)$/.test(entry)) out.push({ full, lines: countLines(full) });
  }
  return out;
}

function countLines(file) {
  const text = readFileSync(file, 'utf8');
  if (text.length === 0) return 0;
  return text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
}

const large = walk(ROOT)
  .filter((file) => file.lines >= THRESHOLD)
  .map((file) => ({ path: relative(ROOT, file.full).replaceAll('\\', '/'), lines: file.lines }))
  .sort((a, b) => b.lines - a.lines);

const rows =
  large.length === 0
    ? '| _(none yet)_ | — | — |'
    : large.map((file) => `| \`${file.path}\` | ${file.lines} | — |`).join('\n');

const markdown = `# Large files

Every code file at or above **${THRESHOLD} lines**. Refactor candidates, not a rule about style.
Generated by \`npm run large-files\`; a stale table fails \`large-files:check\`, which \`npm test\` runs. A
file a refactor takes back under ${THRESHOLD} leaves the list on the next run, and no row is ever
deleted by hand.

| File | Lines | Area |
| --- | --- | --- |
${rows}

Threshold: ${THRESHOLD} lines.
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(TARGET, 'utf8');
  if (current.trim() !== markdown.trim()) {
    console.error('AGENTS/LARGEFILES.md is stale. Run: npm run large-files');
    process.exit(1);
  }
  console.log('AGENTS/LARGEFILES.md is current.');
} else {
  writeFileSync(TARGET, markdown);
  console.log(`wrote ${large.length} file(s) at or above ${THRESHOLD} lines`);
}
